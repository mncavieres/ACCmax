// Write web/js/io/known-displays.js: the published example images the
// workbench recognises when a user opens one of them (also after resizing or
// re-saving). For each: a grey-level thumbnail to recognise it by, its
// source and artery, the heart rate printed on the display, and the
// reference calibration from figures/calibration.json to compare the
// automatic calibration with.
//
// Run after scripts/calibrate-figure-crops.mjs (npm run fit-cases does both).

import { readFileSync, writeFileSync } from 'node:fs';
import { decodePng } from './lib/png.mjs';
import { fingerprint } from '../web/js/io/autocal.js';

const root = new URL('../', import.meta.url);
const cal = JSON.parse(readFileSync(new URL('figures/calibration.json', root), 'utf8'));
const siteFor = (file) => (file.includes('tibial') ? 'ata' : file.includes('brachial') ? 'brachial' : 'other');
const round = (x, d) => Number(x.toFixed(d));

const entries = cal.panels.map((p) => {
  const img = decodePng(readFileSync(new URL(p.file, root)));
  const fp = fingerprint(img);
  return {
    id: p.file.split('/').pop().replace('.png', ''),
    label: p.label,
    subtitle: p.subtitle,
    source: p.source.replace(' See figures/README.md.', ''),
    site: siteFor(p.file),
    width: p.width,
    height: p.height,
    displayedHr: p.displayedHr_bpm,
    scaleLabels: p.evidence.velocityTicks.map((t) => t.cm_s),
    timeAssumption: p.evidence.assumption,
    calibration: {
      region: p.region,
      baselineY: p.baselineY,
      velPerPx: round(p.velPerPx, 9),
      secPerPx: round(p.secPerPx, 9),
    },
    fingerprint: fp.map((v) => v.toString(16).padStart(2, '0')).join(''),
  };
});

const js = `// Generated by scripts/make-known-displays.mjs from figures/calibration.json
// and the crops in figures/crops/: the published example displays the
// workbench recognises. Do not edit by hand.
// fingerprint: ${48 * 16} grey levels (48 × 16 thumbnail), two hex digits each.

export const KNOWN_DISPLAYS = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(new URL('web/js/io/known-displays.js', root), js);
console.log(`web/js/io/known-displays.js: ${entries.length} displays, ${js.length} bytes`);
